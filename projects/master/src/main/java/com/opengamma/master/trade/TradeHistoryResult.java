  public TradeHistoryResult(final Collection<TradeDocument> coll) {
    super(coll);
  }

  //-------------------------------------------------------------------------
  /**
   * Gets the returned Trades from within the documents.
   *
   * @return the Trades, not null
   */
  public List<ManageableTrade> getTrades() {
    final List<ManageableTrade> result = new ArrayList<>();
    if (getDocuments() != null) {
      for (final TradeDocument doc : getDocuments()) {
        result.add(doc.getTrade());
      }
    }
    return result;
  }

  /**
   * Gets the first Trade, or null if no documents.
   *
   * @return the first Trade, null if none
   */
  public ManageableTrade getFirstTrade() {
    return getDocuments().size() > 0 ? getDocuments().get(0).getTrade() : null;
  }

  /**
   * Gets the single result expected from a query.
   * <p>
   * This throws an exception if more than 1 result is actually available.
   * Thus, this method implies an assumption about uniqueness of the queried Trade.
   *
   * @return the matching Trade, not null
   * @throws IllegalStateException if no Trade was found
   */
  public ManageableTrade getSingleSecurity() {
    if (getDocuments().size() != 1) {
      throw new OpenGammaRuntimeException("Expecting zero or single resulting match, and was " + getDocuments().size());
    }
    return getDocuments().get(0).getTrade();
  }

